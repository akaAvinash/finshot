def _bounded_setting(name: str, default: int, minimum: int, maximum: int) -> int:
    value = int(os.environ.get(name, str(default)))
    if not minimum <= value <= maximum:
        raise ValueError(f"{name} must be between {minimum} and {maximum}")
    return value


def _setup_actor(index: int, person: Person) -> tuple[dict[str, str], str]:
    forwarded_for = f"198.51.100.{index + 1}"
    client = person.new_client(forwarded_for=forwarded_for)
    try:
        challenge = person.request_email_code(client)
        code = person.sink.wait_for_code(person.email)
        verified = client.post("/auth/otp/verify", {"challengeId": challenge["challengeId"], "code": code})
        assert verified.status_code == 200, f"Synthetic code verification returned HTTP {verified.status_code}"
        registered = client.adopt_login(verified)
        person.enroll(client)
        assert client.csrf_token
        return {
            "Cookie": "; ".join(f"{key}={value}" for key, value in client.cookies.items()),
            "Origin": "https://qa.tradeo.invalid",
            "X-CSRF-Token": client.csrf_token,
            "X-Forwarded-For": forwarded_for,
        }, registered["user"]["id"]
    finally:
        client.close()


def _measure(
    client: httpx.Client, method: str, path: str, expected_field: str, *, body: dict[str, str] | None = None
) -> tuple[float, str]:
    started = time.perf_counter()
    try:
        response = client.request(method, f"/api/v1{path}", json=body)
        duration = (time.perf_counter() - started) * 1000
        if response.status_code != 200:
            return duration, f"HTTP {response.status_code}"
        payload = response.json()
        if not isinstance(payload, dict) or expected_field not in payload:
            return duration, "unexpected-response-shape"
        return duration, "ok"
    except (httpx.HTTPError, ValueError) as error:
        return (time.perf_counter() - started) * 1000, type(error).__name__


@pytest.mark.req("QA-PERF-001")
@pytest.mark.parametrize(
    ("payload", "outcome"),
    [
        ('{"engine":{}}', "ok"),
        ('{"other":{}}', "unexpected-response-shape"),
        ('["engine"]', "unexpected-response-shape"),
        ('"engine"', "unexpected-response-shape"),
        ("null", "unexpected-response-shape"),
    ],
    ids=["object", "missing-field", "array", "string", "null"],
)
def test_measure_requires_json_object(payload: str, outcome: str) -> None:
    transport = httpx.MockTransport(lambda _: httpx.Response(200, content=payload))
    with httpx.Client(base_url="http://127.0.0.1", transport=transport) as client:
        _, actual = _measure(client, "POST", "/auto-trading/paper/commands", "engine")
    assert actual == outcome


@pytest.mark.req("QA-PERF-001")
@pytest.mark.needs_services
@pytest.mark.slow
@pytest.mark.performance
@pytest.mark.severity("high")
@pytest.mark.timeout(300)
def test_api_load(backend_factory: Callable[..., Backend], smtp_sink: SmtpSink, artifacts_dir: Path) -> None:
    """Hold concurrent, independently authenticated API users and exercise a paper halt burst."""
    users = _bounded_setting("QA_PERF_USERS", 10, 5, 100)
    seconds = _bounded_setting("QA_PERF_SECONDS", 20, 15, 90)
    cold_start = os.environ.get("QA_PERF_COLD_START", "0") == "1"
    backend = backend_factory("performance", TRUSTED_PROXY_HOPS="1")
    backend.settings.assert_disposable()
    people = [Person(backend, smtp_sink) for _ in range(users)]
    # The numbers and addresses are generated by the QA actor and contain no user input.
    values = ",".join(f"('{person.phone}','{person.email}',now())" for person in people)
    run_sql(backend.settings.database_url or "", f"INSERT INTO invites (phone_e164,email,created_at) VALUES {values}")
    with ThreadPoolExecutor(max_workers=min(users, 8)) as pool:
        actors = list(pool.map(_setup_actor, range(users), people))
    assert len({identity for _, identity in actors}) == users, "Every user must have its own test account"

    read_operations = list(READS)
    deadline = 0.0

    def start_traffic() -> None:
        nonlocal deadline
        deadline = time.monotonic() + seconds

    barrier = threading.Barrier(users + 1, action=start_traffic, timeout=30)

    def traffic(index: int, headers: dict[str, str]) -> list[tuple[str, float, str]]:
        rng = random.Random(index)
        offset = index
        samples = []
        with httpx.Client(base_url=backend.base_url, headers=headers, timeout=5, trust_env=False) as client:
            if not cold_start:
                _, warmup = _measure(client, "GET", "/auth/me", "user")
                assert warmup == "ok", f"Connection warm-up failed: {warmup}"
            barrier.wait()
            duration, outcome = _measure(
                client,
                "POST",
                "/auto-trading/paper/commands",
                "engine",
                body={"action": "halt", "confirmation": "STOP"},
            )
            samples.append(("sendPaperCommand", duration, outcome))
            while time.monotonic() < deadline:
                operation = read_operations[offset % len(read_operations)]
                path, field = READS[operation]
                duration, outcome = _measure(client, "GET", path, field)
                samples.append((operation, duration, outcome))
                offset += 1
                time.sleep(min(rng.uniform(0.6, 1.4), max(0.0, deadline - time.monotonic())))
        return samples

    with ThreadPoolExecutor(max_workers=users) as pool:
        pending = [pool.submit(traffic, index, headers) for index, (headers, _) in enumerate(actors)]
        barrier.wait()
        samples = [sample for future in pending for sample in future.result()]

    success: dict[str, list[float]] = defaultdict(list)
    failures: dict[str, Counter[str]] = defaultdict(Counter)
    for operation, duration, outcome in samples:
        if outcome == "ok":
            success[operation].append(duration)
        else:
            failures[operation][outcome] += 1
    operations = {
        operation: {
            "success": len(success[operation]),
            "failures": dict(failures[operation]),
            **latency(success[operation]),
        }
        for operation in [*READS, "sendPaperCommand"]
    }
    errors = sum(sum(counts.values()) for counts in failures.values())
    reads = latency([ms for operation in READS for ms in success[operation]])
    paper_halt = latency(success["sendPaperCommand"])
    report = {
        "users": users,
        "seconds": seconds,
        "connection_profile": "cold" if cold_start else "warm",
        "samples": len(samples),
        "errors": errors,
        "requests_per_second": round(len(samples) / seconds, 2),
        "reads": reads,
        "paper_halt": paper_halt,
        "operations": operations,
    }
    path = artifacts_dir / "api-load.json"
    path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    assert errors == 0, f"Unexpected responses under load: {dict(failures)}"
    assert all(success[operation] for operation in operations), "Some load scenarios received no successful samples"
    assert len(success["sendPaperCommand"]) == users
    assert all(operations[operation]["p95_ms"] <= 500 for operation in READS), "Read operation exceeded 500 ms p95"
    assert paper_halt["p95_ms"] <= 1000, "Paper halt exceeded 1000 ms p95"
